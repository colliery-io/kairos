//! OpenAPI aggregation + dev Swagger UI (KAIROS-T-0023, contract per
//! KAIROS-A-0005 §6).
//!
//! [`ApiDoc`] aggregates every `#[utoipa::path]`-annotated handler in the
//! crate — the spec derives from the same handlers and DTO types
//! (`kairos_client::types*`, A-0015) that serve traffic, so drift is
//! impossible by construction. The A-0012 gate rule ("a handler without
//! annotations fails review") is mechanized by `tests/openapi.rs`, which
//! asserts that the set of `(method, path)` pairs registered on the axum
//! routers equals the set the spec documents.
//!
//! # Routes
//!
//! - `GET /api/openapi.json` — the aggregated OpenAPI 3.x document.
//! - `GET /api/docs` — Swagger UI, mounted ONLY when
//!   [`crate::config::AppConfig::dev_ui`] is set (`KAIROS_DEV_UI=true`);
//!   the route does not exist in a default (production) configuration and
//!   is deliberately NOT part of the spec.
//!
//! # Authentication (decided here, KAIROS-T-0023)
//!
//! Both routes sit behind the standard auth → tenant middleware stack,
//! exactly like every other `/api` route: the spec enumerates the
//! deployment's full API surface and stays deployment-internal; any org
//! member can fetch it. The **unauthenticated** distribution channel is
//! the CI build artifact (`openapi.json` uploaded per run, A-0005 §6
//! "the spec is a CI artifact per release"), generated by the
//! `write_spec_artifact` test in `tests/openapi.rs` without a running
//! server. Dev Swagger UI callers authenticate like any API client
//! (curl, or a header-injecting browser extension in dev).
//!
//! # WebSocket channel
//!
//! OpenAPI covers the REST surface only. The `GET /ws/events` push
//! channel (A-0005 §5) is documented in `docs/api/events.md` and in the
//! [`crate::ws`] module docs; the spec's `info.description` points there.

