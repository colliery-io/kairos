/// The aggregated OpenAPI document (also consumed by `tests/openapi.rs`,
/// whose `write_spec_artifact` test generates the CI artifact).
pub fn spec() -> utoipa::openapi::OpenApi {
    ApiDoc::openapi()
}

/// The serialized spec, built once per process.
static SPEC_JSON: LazyLock<String> = LazyLock::new(|| {
    serde_json::to_string_pretty(&spec()).expect("the derived OpenAPI document serializes")
});

/// Build the module's routes. Merged into the protected `/api` chain by
/// [`crate::app::router`] (behind auth → tenant, see module docs);
/// `dev_ui` comes from [`crate::config::AppConfig::dev_ui`].
pub fn router(dev_ui: bool) -> Router<AppState> {
    let router = Router::new().route("/api/openapi.json", get(openapi_json));
    if dev_ui {
        router.route("/api/docs", get(swagger_ui))
    } else {
        router
    }
}

/// Serve the aggregated spec.
#[utoipa::path(
    get,
    path = "/api/openapi.json",
    tag = "meta",
    responses(
        (status = 200, description = "This OpenAPI 3.x document (application/json)"),
        (status = 401, description = "Missing/invalid token", body = kairos_client::types::ErrorEnvelope),
        (status = 403, description = "Not a member of the organization", body = kairos_client::types::ErrorEnvelope),
    ),
)]
pub(crate) async fn openapi_json() -> impl IntoResponse {
    (
        [(header::CONTENT_TYPE, "application/json")],
        SPEC_JSON.as_str(),
    )
}

