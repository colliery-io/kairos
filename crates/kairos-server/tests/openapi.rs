/// Collect every `.rs` file under `dir`, recursively.
fn rust_sources(dir: &FsPath, out: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).expect("readable src dir") {
        let path = entry.expect("dir entry").path();
        if path.is_dir() {
            rust_sources(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

/// The argument text of one `.route(` call: everything up to the paren
/// that balances the opening one, plus how many bytes were consumed.
fn balanced_args(text: &str) -> (&str, usize) {
    let mut depth = 1usize;
    for (i, c) in text.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 {
                    return (&text[..i], i);
                }
            }
            _ => {}
        }
    }
    panic!("unbalanced .route( arguments: {text:?}");
}

/// The HTTP methods named in a `.route(...)` argument list: `get(`,
/// `post(`, ... tokens not preceded by an identifier character (so
/// `get(get_strategy)` counts `get` once and ignores the handler name).
fn methods_in(args: &str) -> Vec<String> {
    let mut methods = Vec::new();
    for method in ["get", "post", "put", "patch", "delete", "head", "options"] {
        let needle = format!("{method}(");
        let mut from = 0;
        while let Some(pos) = args[from..].find(&needle) {
            let at = from + pos;
            let preceded_by_ident = at > 0
                && args[..at]
                    .chars()
                    .next_back()
                    .is_some_and(|c| c.is_alphanumeric() || c == '_');
            if !preceded_by_ident {
                methods.push(method.to_uppercase());
            }
            from = at + needle.len();
        }
    }
    methods.sort();
    methods.dedup();
    methods
}

/// Scan the crate's `src/` for `.route("literal", ...)` registrations and
/// return every `(METHOD, path)` pair whose path starts with `/api`.
/// Comment lines are stripped so doc examples cannot pollute the set.
fn registered_api_routes() -> BTreeSet<(String, String)> {
    let src = FsPath::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut files = Vec::new();
    rust_sources(&src, &mut files);
    assert!(!files.is_empty(), "no sources under {src:?}");

    let mut routes = BTreeSet::new();
    for file in &files {
        // src/mcp is quarantined (unmounted) pending KAIROS-T-0026 resume; its
        // routes are non-/api MCP protocol surface and use const paths this
        // literal scanner cannot read. T-0026 must either keep its routes
        // outside /api (they are) or extend this scanner when un-quarantining.
        if file.components().any(|c| c.as_os_str() == "mcp") {
            continue;
        }
        let raw = std::fs::read_to_string(file).expect("readable source file");
        let code: String = raw
            .lines()
            .filter(|line| !line.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join("\n");
        let mut rest = code.as_str();
        while let Some(pos) = rest.find(".route(") {
            let args_start = pos + ".route(".len();
            let (args, consumed) = balanced_args(&rest[args_start..]);
            let path = args
                .split('"')
                .nth(1)
                .unwrap_or_else(|| panic!("{file:?}: .route( without a path literal: {args:?}"));
            if path.starts_with("/api") {
                let methods = methods_in(args);
                assert!(
                    !methods.is_empty(),
                    "{file:?}: no methods recognized in .route({args:?})"
                );
                for method in methods {
                    routes.insert((method, path.to_string()));
                }
            }
            rest = &rest[args_start + consumed..];
        }
    }
    routes
}

/// The `(METHOD, path)` pairs the aggregated spec documents.
fn documented_api_routes(spec_json: &Value) -> BTreeSet<(String, String)> {
    let paths = spec_json["paths"]
        .as_object()
        .expect("spec has a paths object");
    let mut routes = BTreeSet::new();
    for (path, item) in paths {
        for method in item.as_object().expect("path item object").keys() {
            match method.as_str() {
                "get" | "post" | "put" | "patch" | "delete" | "head" | "options" | "trace" => {
                    routes.insert((method.to_uppercase(), path.clone()));
                }
                // parameters/summary/description keys are not operations.
                _ => {}
            }
        }
    }
    routes
}

