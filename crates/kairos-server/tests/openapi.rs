/// A raw in-process request for non-JSON responses (the Swagger UI page):
/// status, `content-type`, body text.
async fn raw_get(router: &Router, uri: &str, token: Option<&str>) -> (StatusCode, String, String) {
    let mut builder = Request::builder().method(Method::GET).uri(uri);
    if let Some(token) = token {
        builder = builder.header("authorization", format!("Bearer {token}"));
    }
    let response = router
        .clone()
        .oneshot(
            builder
                .header("x-tenant", "acme")
                .body(Body::empty())
                .expect("request"),
        )
        .await
        .expect("response");
    let status = response.status();
    let content_type = response
        .headers()
        .get("content-type")
        .map(|v| v.to_str().unwrap_or_default().to_string())
        .unwrap_or_default();
    let bytes = response
        .into_body()
        .collect()
        .await
        .expect("body")
        .to_bytes();
    (status, content_type, String::from_utf8_lossy(&bytes).into())
}

/// Substitute every `{param}` in a spec path with a literal segment so it
/// matches the axum route pattern (the probe never reaches a handler, so
/// the value is irrelevant).
fn probe_uri(spec_path: &str) -> String {
    spec_path
        .split('/')
        .map(|segment| {
            if segment.starts_with('{') && segment.ends_with('}') {
                "probe"
            } else {
                segment
            }
        })
        .collect::<Vec<_>>()
        .join("/")
}

#[tokio::test]
async fn openapi_endpoint_against_live_stack() {
    // --- scratch database + tenant -------------------------------------------
    let mut admin_conn = recreate_scratch_db(SCRATCH_DB);
    let scratch_url = with_database(&common::admin_database_url(), SCRATCH_DB);
    let mut conn = PgConnection::establish(&scratch_url).expect("connecting to scratch database");
    run_public_migrations(&mut conn).expect("running public migrations");
    provision_tenant(&mut conn, "acme", "Acme Inc").expect("provisioning acme");
    let org_id: Uuid = organizations::table
        .filter(organizations::slug.eq("acme"))
        .select(organizations::id)
        .first(&mut conn)
        .expect("acme org row");

    // --- production router + live token ---------------------------------------
    let http = reqwest::Client::new();
    let alice = user_token(&http, "alice").await;
    let pool = TenantPool::new(&scratch_url, 4).await.expect("pool");
    let auth = Arc::new(
        Authenticator::discover(ISSUER, AUDIENCE)
            .await
            .expect("OIDC discovery against live Dex"),
    );
    // KAIROS-T-0203: local auth ON for the probe below. `/api/login` and
    // `/api/logout` are documented unconditionally — the spec is the API contract —
    // but they are ROUTED only when KAIROS_LOCAL_AUTH is on. A probe router with
    // them off would report them as documented-but-unrouted, which is the very
    // drift this test exists to catch, so the router under probe is the one that
    // has every documented route.
    let mut probe_config = base_config(&scratch_url);
    probe_config.local_auth = true;
    let router = app::router(app::state_with(probe_config, pool.clone(), auth.clone()));

    // --- auth posture: the spec sits behind the standard stack ---------------
    let (status, body) = request(
        &router,
        Method::GET,
        "/api/openapi.json",
        None,
        TENANT_HEADERS,
        None,
    )
    .await;
    assert_eq!(status, StatusCode::UNAUTHORIZED, "{body}");
    assert_eq!(error_code(&body), "UNAUTHORIZED");

    // First authenticated request JIT-provisions alice; she is not an org
    // member yet, so membership 403 — then grant it.
    let (status, body) = request(
        &router,
        Method::GET,
        "/api/openapi.json",
        Some(&alice),
        TENANT_HEADERS,
        None,
    )
    .await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
    assert_eq!(error_code(&body), "MEMBERSHIP_REQUIRED");
    let alice_id: Uuid = users::table
        .filter(users::email.eq("alice@kairos.test"))
        .select(users::id)
        .first(&mut conn)
        .expect("alice provisioned");
    diesel::insert_into(organization_members::table)
        .values(NewOrganizationMember {
            organization_id: org_id,
            user_id: alice_id,
            role: OrgRole::Member,
        })
        .execute(&mut conn)
        .expect("granting alice membership");

    // --- GET /api/openapi.json: 3.x, byte-identical to the aggregation -------
    let (status, served) = request(
        &router,
        Method::GET,
        "/api/openapi.json",
        Some(&alice),
        TENANT_HEADERS,
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{served}");
    let version = served["openapi"].as_str().expect("openapi version");
    assert!(version.starts_with("3."), "expected 3.x, got {version}");
    assert_eq!(
        served,
        serde_json::to_value(spec()).expect("spec serializes"),
        "the served document must be exactly the aggregated spec"
    );
    for family in ["/api/strategies", "/api/search", "/api/boards"] {
        assert!(
            served["paths"].get(family).is_some(),
            "served spec is missing {family}"
        );
    }

    // --- probe: every documented path exists on the production router --------
    // Token-less requests 404 ONLY from the bare-router fallback (matched
    // routes answer 401 from the auth layer first) — see module docs.
    for (method, path) in documented_api_routes(&served) {
        let uri = probe_uri(&path);
        let (status, _body) = request(
            &router,
            Method::from_bytes(method.as_bytes()).expect("method"),
            &uri,
            None,
            &[],
            None,
        )
        .await;
        assert_ne!(
            status,
            StatusCode::NOT_FOUND,
            "{method} {path} is documented in the spec but not routed \
             (probe {uri} hit the router fallback)"
        );
    }

    // --- Swagger UI: present with KAIROS_DEV_UI, absent by default -----------
    let mut dev_config = base_config(&scratch_url);
    dev_config.dev_ui = true;
    let dev_router = app::router(app::state_with(dev_config, pool, auth));

    let (status, content_type, page) = raw_get(&dev_router, "/api/docs", Some(&alice)).await;
    assert_eq!(status, StatusCode::OK, "{page}");
    assert!(content_type.starts_with("text/html"), "{content_type}");
    assert!(page.contains("SwaggerUIBundle"), "{page}");
    assert!(page.contains("/api/openapi.json"), "{page}");

    let (status, _, _) = raw_get(&router, "/api/docs", Some(&alice)).await;
    assert_eq!(
        status,
        StatusCode::NOT_FOUND,
        "/api/docs must not exist without KAIROS_DEV_UI"
    );

    drop_scratch_db(&mut admin_conn, SCRATCH_DB);
}
