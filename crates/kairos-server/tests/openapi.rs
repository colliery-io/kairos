/// THE completeness gate (module docs): registered routes == spec paths.
#[test]
fn registered_routes_and_spec_paths_match_exactly() {
    let spec_json = serde_json::to_value(spec()).expect("spec serializes");
    let mut registered = registered_api_routes();
    for (method, path, _reason) in EXCLUDED_FROM_SPEC {
        assert!(
            registered.remove(&(method.to_string(), path.to_string())),
            "stale EXCLUDED_FROM_SPEC entry: {method} {path} is not registered anywhere"
        );
    }
    let documented = documented_api_routes(&spec_json);

    let missing_from_spec: Vec<_> = registered.difference(&documented).collect();
    let missing_from_router: Vec<_> = documented.difference(&registered).collect();
    assert!(
        missing_from_spec.is_empty() && missing_from_router.is_empty(),
        "route/spec drift (A-0005 §6).\n\
         Registered but NOT in the OpenAPI spec (annotate the handler with \
         #[utoipa::path] and add it to api::openapi::ApiDoc): {missing_from_spec:?}\n\
         In the spec but NOT registered on any router: {missing_from_router:?}"
    );
}

/// The spec is 3.x and covers every expected path family (spot list —
/// the exact-set test above is the real gate; this documents intent).
#[test]
fn spec_is_openapi_3_and_covers_expected_families() {
    let spec_json = serde_json::to_value(spec()).expect("spec serializes");
    let version = spec_json["openapi"].as_str().expect("openapi version");
    assert!(version.starts_with("3."), "expected 3.x, got {version}");

    let paths = spec_json["paths"].as_object().expect("paths object");
    for expected in [
        "/api/strategies",
        "/api/strategies/{short_code}",
        "/api/strategies/{short_code}/transition",
        "/api/initiatives",
        "/api/tasks",
        "/api/documents",
        "/api/adrs",
        "/api/search",
        "/api/boards",
        "/api/boards/{id}/items",
        "/api/teams",
        "/api/delivery-streams",
        "/api/members",
        "/api/relationships",
        "/api/{entity_type}/{short_code}/relationships",
        "/api/{entity_type}/{short_code}/metadata",
        "/api/{entity_type}/{short_code}/history",
        "/api/metadata-definitions",
        "/api/templates",
        "/api/activity",
        "/api/admin/tenants",
        "/api/whoami",
        "/api/openapi.json",
    ] {
        assert!(paths.contains_key(expected), "spec is missing {expected}");
    }
    // The dev UI is deliberately undocumented (EXCLUDED_FROM_SPEC).
    assert!(!paths.contains_key("/api/docs"));

    // DTO schemas were aggregated (the deep resolution check is the
    // containerized validator run recorded in KAIROS-T-0023).
    let schemas = spec_json["components"]["schemas"]
        .as_object()
        .expect("components.schemas");
    for expected in ["Strategy", "Task", "SearchRequest", "ErrorEnvelope"] {
        assert!(
            schemas.contains_key(expected),
            "components.schemas is missing {expected}"
        );
    }
}

/// operationIds must be unique across the aggregated document.
#[test]
fn operation_ids_are_unique() {
    let spec_json = serde_json::to_value(spec()).expect("spec serializes");
    let mut seen: BTreeMap<String, (String, String)> = BTreeMap::new();
    for (method, path) in documented_api_routes(&spec_json) {
        let id = spec_json["paths"][&path][method.to_lowercase()]["operationId"]
            .as_str()
            .unwrap_or_else(|| panic!("{method} {path} has no operationId"))
            .to_string();
        if let Some(previous) = seen.insert(id.clone(), (method.clone(), path.clone())) {
            panic!("duplicate operationId {id:?}: {previous:?} vs ({method}, {path})");
        }
    }
}

/// Generate the CI artifact: write the spec to `target/openapi.json`
/// (workspace target dir). The CI workflow runs exactly this test and
/// uploads the file; the containerized validator runs against it too.
#[test]
fn write_spec_artifact() {
    let out = FsPath::new(env!("CARGO_MANIFEST_DIR")).join("../../target/openapi.json");
    let json = serde_json::to_string_pretty(&spec()).expect("spec serializes");
    std::fs::write(&out, &json).expect("writable target dir");
    // Round-trip: what CI uploads is parseable JSON.
    let parsed: Value = serde_json::from_str(&json).expect("artifact parses");
    assert!(parsed["openapi"].as_str().is_some());
    println!("wrote {}", out.display());
}

