//! KAIROS-T-0023 — OpenAPI aggregation (`/api/openapi.json`) and the dev
//! Swagger UI (`/api/docs`, `KAIROS_DEV_UI`).
//!
//! # The route-vs-spec completeness test (A-0005 §6 / A-0012 enforcement)
//!
//! axum's `Router` cannot be introspected, so completeness is asserted in
//! two mechanized halves:
//!
//! 1. [`registered_routes_and_spec_paths_match_exactly`] (no services
//!    needed) scans this crate's `src/` for `.route("...", ...)`
//!    registrations, extracts every `(method, path)` pair under `/api`,
//!    and asserts SET EQUALITY with the `(method, path)` pairs the spec
//!    documents. **Failure mode**: a new route registered anywhere in
//!    `src/` without a `#[utoipa::path]` handler wired into
//!    `api::openapi::ApiDoc` fails this test (it appears in the
//!    registered set but not the spec), as does a spec entry whose route
//!    was never registered. Blind spot: a route registered through
//!    something other than a `.route("literal", ...)` call would escape
//!    the scan — the probe below catches the documented-but-unmounted
//!    half, and this crate registers routes exclusively via `.route`.
//! 2. The probe inside [`openapi_endpoint_against_live_stack`] walks
//!    every path in the served spec against the REAL production router
//!    and asserts a non-404 answer (an unauthenticated request reaches
//!    the auth layer only if the route exists; the bare-router fallback
//!    is the only 404 source for a token-less request). This catches a
//!    scanned-and-documented route whose module router was never merged
//!    into `app::router`. It cannot catch method drift (the auth layer
//!    answers 401 before method dispatch) — half 1 owns methods.
//!
//! The CI artifact is generated by [`write_spec_artifact`] (pure, no
//! services), uploaded by the workflow's "OpenAPI artifact" step.

